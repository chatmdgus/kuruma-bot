const recent = new Map();   // 대사 묶음별 최근에 쓴 번호 (반복 방지)
function pick(key, lines) {
  const used = recent.get(key) || [];
  const pool = lines.map((_, i) => i).filter((i) => !used.includes(i));
  const i = pool[Math.floor(Math.random() * pool.length)];
  used.push(i);
  while (used.length > Math.floor(lines.length / 2)) used.shift();   // 절반은 쉬게
  recent.set(key, used);
  return lines[i];
}

module.exports = function (client) {
  const last = new Map();   // 채널별 마지막 츳코미 시각
  const lastReact = new Map();
  let lastLonely = 0;
  let lonelyTimer = null, lonelyAuthor = null, lastMsgAt = Date.now(), lastAuthor = null;
  let hookCache = null;

  async function say(channel, [ko, ja]) {
    if (!hookCache) {
      const hooks = await channel.fetchWebhooks();
      hookCache = hooks.find((h) => h.owner?.id === client.user.id) || await channel.createWebhook({ name: 'translator' });
    }
    const kuruma = await client.users.fetch(KURUMA_ID).catch(() => null);
    await hookCache.send({
      content: `${ko}\n-# ${ja}`,
      username: kuruma?.username || '쿠루마봇・クルマボット',
      avatarURL: kuruma?.displayAvatarURL(),
      allowedMentions: { parse: [] },
    });
  }

  client.on('messageCreate', async (m) => {
    try {
      const chId = process.env.TSUKKOMI_CHANNEL || CH_DEFAULT;
      if (m.channelId !== chId || m.author?.bot || m.webhookId) return;
      const text = (m.content || '').trim();

      // 5분 무응답: 한동안(10분) 조용하다가 누가 말을 꺼냈는데 아무도 대답 안 할 때만.
      // 다른 사람이 말하면 취소, 같은 사람이 이어 말하면 다시 5분. 인사로 끝내는 말은 제외
      const opened = !lonelyTimer && lastAuthor !== m.author.id && Date.now() - lastMsgAt > 10 * 60e3;
      const sameStreak = lonelyTimer && lonelyAuthor === m.author.id;
      if (lonelyTimer) { clearTimeout(lonelyTimer); lonelyTimer = null; }
      lastMsgAt = Date.now(); lastAuthor = m.author.id;
      if ((opened || sameStreak) && !RULES.find(([n]) => n === 'bye')[1].test(text)) {
        lonelyAuthor = m.author.id;
        lonelyTimer = setTimeout(() => {
          lonelyTimer = null;
          if (Date.now() - lastLonely < LONELY_COOLDOWN || Math.random() >= 0.6) return;
          lastLonely = Date.now();
          say(m.channel, pick('lonely', LONELY)).then(() => console.log('[tsukkomi] lonely')).catch((e) => console.error('[tsukkomi]', e.message));
        }, LONELY_WAIT);
      }

      if (!text || text.startsWith('!') || text.length > 200) return;
      if (/^(야\s*쿠루마\s*봇|(ねえ|ねぇ)[、,\s]*クルマ\s*ボット)/.test(text)) return;   // 주인이 쿠루마봇 부를 때는 끼지 않음
      if (/[파프려리곤들심워다]지\s*(않|마)|안\s*(졸|배고|피곤|힘들|심심|추워|더워|씻|먹)|(眠|寒|暑|だる|しんど)くない|すいてない|疲れてない|入らない|食べない/.test(text)) return; // TK_NEG: 부정문은 패스
      const rule = RULES.find(([, re]) => re.test(text));
      if (!rule) return;
      // 70%는 말로, 나머지(또는 말 쿨다운 중)는 이모지 반응. 둘 다 30초에 한 번
      const talk = Date.now() - (last.get(chId) || 0) >= COOLDOWN && Math.random() < +(process.env.TSUKKOMI_RATE || 0.7);
      if (!talk) {
        if (Date.now() - (lastReact.get(chId) || 0) < REACT_COOLDOWN) return;
        lastReact.set(chId, Date.now());
        await m.react(rule[2]).catch(() => {});
        console.log(`[tsukkomi] ${rule[0]} (react)`);
        return;
      }
      last.set(chId, Date.now());
      await new Promise((r) => setTimeout(r, 3000 + Math.random() * 3000));   // 번역 글 뒤에 나오게
      await say(m.channel, pick(rule[0], rule[3]));
      console.log(`[tsukkomi] ${rule[0]}`);
    } catch (e) { console.error('[tsukkomi]', e.message); }
  });
};
