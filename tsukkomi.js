module.exports = function (client) {
  const last = new Map();   // 채널별 마지막 츳코미 시각
  let hookCache = null;

  client.on('messageCreate', async (m) => {
    try {
      const chId = process.env.TSUKKOMI_CHANNEL || CH_DEFAULT;
      if (m.channelId !== chId || m.author?.bot || m.webhookId) return;
      const text = (m.content || '').trim();
      if (!text || text.startsWith('!') || text.length > 200) return;
      if (/^(야\s*쿠루마\s*봇|(ねえ|ねぇ)[、,\s]*クルマ\s*ボット)/.test(text)) return;   // 주인이 쿠루마봇 부를 때는 끼지 않음
      if (Date.now() - (last.get(chId) || 0) < COOLDOWN) return;
      const rule = RULES.find(([, re]) => re.test(text));
      if (!rule) return;
      if (Math.random() >= +(process.env.TSUKKOMI_RATE || 0.12)) return;
      last.set(chId, Date.now());

      const [ko, ja] = rule[2][Math.floor(Math.random() * rule[2].length)];
      await new Promise((r) => setTimeout(r, 3000 + Math.random() * 3000));   // 번역 글 뒤에 나오게
      if (!hookCache) {
        const hooks = await m.channel.fetchWebhooks();
        hookCache = hooks.find((h) => h.owner?.id === client.user.id) || await m.channel.createWebhook({ name: 'translator' });
      }
      const kuruma = await client.users.fetch(KURUMA_ID).catch(() => null);
      await hookCache.send({
        content: `${ko}\n-# ${ja}`,
        username: kuruma?.username || '쿠루마봇・クルマボット',
        avatarURL: kuruma?.displayAvatarURL(),
        allowedMentions: { parse: [] },
      });
      console.log(`[tsukkomi] ${rule[0]}`);
    } catch (e) { console.error('[tsukkomi]', e.message); }
  });
};
